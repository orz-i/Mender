//go:build !windows

package processisolation

import (
	"context"
	"os/exec"
	"runtime"
	"strconv"
	"strings"
	"syscall"
	"testing"
	"time"

	runtimegovernancedomain "github.com/orz-i/Mender/backend/internal/runtimegovernance/domain"
)

// Background Agent processes need their own OS Session (not just a PGID).
// A child that inherits the interactive Wails terminal can otherwise stop
// under job control, while its supervising Task continues to heartbeat.
func TestManagedUnixCommandDetachesControllingTerminalAndRetainsGroupCancellation(t *testing.T) {
	root := t.TempDir()
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	launcher := newLauncher(runtime.GOOS, "", root, "none")
	cmd, err := launcher.Command(ctx, runtimegovernancedomain.IsolationHost, CommandSpec{
		Executable: "/bin/sh", Arguments: []string{"-c", "sleep 30"},
		WorkingDirectory: root, PermittedRoot: root,
	})
	if err != nil {
		t.Fatal(err)
	}
	if cmd.SysProcAttr == nil || !cmd.SysProcAttr.Setsid || cmd.SysProcAttr.Setpgid ||
		cmd.SysProcAttr.Setctty || cmd.SysProcAttr.Foreground {
		t.Fatalf("command does not detach OS Session: %+v", cmd.SysProcAttr)
	}
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	waited := false
	defer func() {
		if !waited {
			cancel()
			_ = cmd.Process.Kill()
			_ = cmd.Wait()
		}
	}()
	pgid, err := syscall.Getpgid(cmd.Process.Pid)
	if err != nil || pgid != cmd.Process.Pid {
		t.Fatalf("child is not a session/group leader: pid=%d pgid=%d err=%v",
			cmd.Process.Pid, pgid, err)
	}
	// Outside a controlling TTY this still validates OS Session creation.
	// On an interactive Mac the following also catches unwanted tty inheritance.
	if runtime.GOOS == "darwin" {
		output, err := exec.Command( // #nosec G204 -- PID is numeric and generated by this test's own started child.
			"/bin/ps", "-p", strconv.Itoa(cmd.Process.Pid), "-o", "tty=",
		).CombinedOutput()
		if err != nil || strings.TrimSpace(string(output)) != "??" {
			t.Fatalf("child inherited a controlling tty: %q, %v", strings.TrimSpace(string(output)), err)
		}
	}
	start := time.Now()
	cancel()
	err = cmd.Wait()
	waited = true
	if err == nil {
		t.Fatal("cancelled child unexpectedly exited successfully")
	}
	if time.Since(start) > 3*time.Second {
		t.Fatal("group cancellation did not promptly reap the child")
	}
}
