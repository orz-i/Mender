// Package v2 contains immutable, disposable Provider-v2 database fixtures
// exclusively for verifying the forward-only Tool hard-cut migration.
// Production v3 Runtime never imports or opens these assets.
package v2

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	_ "embed"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"testing"
)

//go:embed testdata/empty-provider-v2.sqlite.gz
var emptyLegacyV2 []byte

const emptyLegacyV2SHA256 = "d4bd00ea15142382b317e8a27e32c6afd995929b17341b794d9c57f684157628"

// EmptyDatabase copies a historical, schema-version-pinned v2 SQLite image
// into a test-owned temporary directory. It contains no user records, secrets,
// runtime tasks, active leases or configured resources. It is NEVER an upgrade
// or a second runtime composition.
func EmptyDatabase(t testing.TB) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "provider-v2.sqlite")
	reader, err := gzip.NewReader(bytes.NewReader(emptyLegacyV2))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = reader.Close() }()
	// #nosec G304 -- path is generated by t.TempDir and O_EXCL prevents replacement.
	target, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		t.Fatal(err)
	}
	hash := sha256.New()
	count, err := io.Copy(io.MultiWriter(target, hash), io.LimitReader(reader, 2<<20))
	if err != nil {
		_ = target.Close()
		t.Fatal(err)
	}
	if err := target.Close(); err != nil {
		t.Fatal(err)
	}
	if count != 712704 || fmt.Sprintf("%x", hash.Sum(nil)) != emptyLegacyV2SHA256 {
		t.Fatal("historical v2 fixture checksum or size changed")
	}
	return path
}
